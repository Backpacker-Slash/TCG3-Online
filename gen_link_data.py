#!/usr/bin/env python3
"""Generate tcg2_link_data.js for the browser client from the build outputs.

  python3 online/gen_link_data.py [poketcg2.sym] [online/tcg2_link_data.js]

It exports the WRAM offsets the client needs (looked up by symbol name, so they
follow the ROM whenever wram.asm changes) and the character tables used to show
player names (from src/constants/charmaps.asm).
"""
import json, os, re, sys

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sym_path = sys.argv[1] if len(sys.argv) > 1 else os.path.join(root, 'poketcg2.sym')
out_path = sys.argv[2] if len(sys.argv) > 2 else os.path.join(root, 'online', 'tcg2_link_data.js')

# client name -> ROM symbol
SYMBOLS = {
    'serialOp': 'wSerialOp',
    'serialFlags': 'wSerialFlags',
    'linkReady': 'wLinkReady',
    'sendCount': 'wSerialSendBufToggle',
    'sendReadIdx': 'wSerialSendBufIndex',
    'sendWriteIdx': 'wcb80',
    'sendBuf': 'wSerialSendBuf',
    'recvCount': 'wSerialRecvCounter',
    'recvReadIdx': 'wcba3',
    'recvWriteIdx': 'wSerialRecvIndex',
    'recvBuf': 'wSerialRecvBuf',
    'nameBuffer': 'wNameBuffer',      # the opponent's name block, after the exchange
    'ownNameBuffer': 'wDefaultText',  # our own name block, as sent to the opponent
    'playerDeck': 'wPlayerDeck',
    'opponentDeck': 'wOpponentDeck',
}
syms = {}
for line in open(sym_path):
    m = re.match(r'([0-9a-f]+):([0-9a-f]+) (\S+)$', line.strip())
    if m:
        syms[m.group(3)] = (int(m.group(1), 16), int(m.group(2), 16))

offsets = {}
for key, name in SYMBOLS.items():
    bank, addr = syms[name]
    if bank != 0 or not (0xC000 <= addr < 0xD000):
        sys.exit('%s (%s) is not in WRAM0: %02x:%04x' % (key, name, bank, addr))
    offsets[key] = addr - 0xC000

# character tables for names: (set byte, code) -> char
consts = {}
for line in open(os.path.join(root, 'src/constants/text_constants.asm')):
    m = re.match(r'DEF (TX_\w+)\s+EQU \$([0-9a-fA-F]+)', line)
    if m:
        consts[m.group(1)] = int(m.group(2), 16)
chars = {}
for line in open(os.path.join(root, 'src/constants/charmaps.asm')):
    m = re.match(r'\s*fwcharmap (TX_\w+), "(.+)", \$([0-9a-fA-F]+)', line)
    if m:
        chars.setdefault(consts[m.group(1)], {})[int(m.group(3), 16)] = m.group(2)
table = {str(k): {str(c): ch for c, ch in v.items()} for k, v in chars.items()}

with open(out_path, 'w', encoding='utf-8') as f:
    f.write('// generated by online/gen_link_data.py from poketcg2.sym and charmaps.asm - do not edit\n')
    f.write('window.TCG2_LINK_OFFSETS = %s;\n' % json.dumps(offsets, indent=2))
    f.write('// player name characters: TCG2_NAME_CHARS[setByte][code]; names are pairs of (setByte, code)\n')
    f.write('window.TCG2_NAME_CHARS = %s;\n' % json.dumps(table, ensure_ascii=False))
print('wrote', out_path, '(%d offsets, %d char sets)' % (len(offsets), len(table)))
