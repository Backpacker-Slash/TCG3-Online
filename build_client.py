#!/usr/bin/env python3
"""Build the TCG2 online duel client from the TCG1 online link client.

  python3 online/build_client.py path/to/poketcg-online-link/index.html [online/index.html]

The TCG1 client's page (look, controls, key mapping, save storage, PeerJS room
handling, chat) is kept. Everything that was specific to the TCG1 ROM is removed
(custom portraits, RAM-synced decks and duel variables, play time hack) and the
link is replaced by tcg2_link.js, which carries the unmodified TCG2 link protocol.
"""
import os
import sys

here = os.path.dirname(os.path.abspath(__file__))
src_path = sys.argv[1]
out_path = sys.argv[2] if len(sys.argv) > 2 else os.path.join(here, 'index.html')
s = open(src_path, encoding='utf-8').read()

BAR = '        // ============================================================\n'


def once(text, old):
    assert text.count(old) == 1, 'expected exactly one match for %r, got %d' % (old[:70], text.count(old))


def replace(old, new):
    global s
    once(s, old)
    s = s.replace(old, new)


def cut(start, end, new=''):
    """replace everything from start (inclusive) to end (exclusive)"""
    global s
    once(s, start)
    i = s.index(start)
    j = s.index(end, i + len(start))
    s = s[:i] + new + s[j:]


# ---------------------------------------------------------------- head / html
replace('<title>Pokemon TCG Online Link Duel</title>', '<title>Pokemon TCG 2 Online Link Duel</title>')
s = s.replace('Pokemon TCG Online Link Duel"', 'Pokemon TCG 2 Online Link Duel"')
s = s.replace('Pokemon TCG Online Duel Client with WebRTC Lockstep RAM-Sync, Game Boy tactile controls, and mobile touch support.',
              'Pokemon TCG 2 (GB2) link duels over the internet: the link cable is replaced by WebRTC, with Game Boy tactile controls and mobile touch support.')
replace('<script src="peerjs.min.js"></script>',
        '<script src="peerjs.min.js"></script>\n    <script src="tcg2_link_data.js"></script>\n    <script src="tcg2_link.js"></script>')
cut('            <!-- Custom Avatar (48', '            <!-- Desktop Keyboard Controls Cheatsheet')

# ----------------------------------------------------------------- constants
cut(BAR + '        // RAM OFFSETS', BAR + '        // GLOBAL STATE', BAR + '''        // LINK OFFSETS (generated by online/gen_link_data.py)
''' + BAR + '''        const LINK_OFFSETS = window.TCG2_LINK_OFFSETS;
        const NAME_CHARS = window.TCG2_NAME_CHARS;
        const NAME_CHARS_PER_NAME = 6;     // MAX_PLAYER_NAME_CHARS
        const NAME_BLOCK_GENDER = 0x0d;    // NAME_BUFFER_GENDER: 0 = boy, 1 = girl

''')

cut(BAR + '        // GLOBAL STATE', '        // FIFO Queue for serial packets', BAR + '''        // GLOBAL STATE
''' + BAR + '''        let isHost = false;
        let module = null;
        let emulatorPtr = null;
        let audio = null;
        let joypadPtr = null;
        let keyFuncs = {};
        let animationFrameReq = null;
        let wramCachedPtr = null;
        let peer = null;
        let connection = null;
        let myRoomCode = null;
        let remotePlayerName = "OPPONENT";
        let currentRomBuffer = null;
        let originalRomBuffer = null;
        let currentSavBuffer = null;
        let liveRomPtr = null;
        let liveRomSize = 0;
        let link = null;           // Tcg2Link, the cable between the two emulators
        let lastP1Visual = null;
        let lastP2Visual = null;
        let lastNameCheck = 0;

''')

# -------------------------------------------- link state helpers + char map
cut('        // FIFO Queue for serial packets', BAR + '        // CHARACTER MAP', '''        // Link liveness (explicit bye on tab close, no periodic traffic)
        let linkAlive = false;

        function setFlag(id, on) {
            const el = $(id);
            if (el) el.className = `w-3 h-3 rounded-full ${on ? 'bg-green-500 shadow-[0_0_8px_#22c55e]' : 'bg-slate-700'}`;
        }

        function onLinkEvent(name, detail) {
            if (name === 'ready') setFlag('p1-flag', detail);
            else if (name === 'peer-ready') setFlag('p2-flag', detail);
            else if (name === 'linked') {
                addChatMessage('SYSTEM', detail.master ? 'Link established (you are the master).' : 'Link established.');
            } else if (name === 'unlinked') {
                setFlag('p1-flag', false);
                setFlag('p2-flag', false);
                if (detail === 'peer-gone') addChatMessage('SYSTEM', 'The link was cut: your partner is gone.');
            }
        }

        /** (Re)create the cable for the current connection. */
        function makeLink() {
            link = new Tcg2Link({
                isHost,
                offsets: LINK_OFFSETS,
                send: (msg) => { if (connection?.open) connection.send(msg); },
                onEvent: onLinkEvent,
            });
            link.peerConnected();
        }

        /** Soft-reset link handshake after emulator re-init. Keeps PeerJS open. */
        function resetLinkSyncState({ notifyPeer = false } = {}) {
            if (link) {
                link.resetSession();
                if (notifyPeer && connection?.open) connection.send({ type: 'ready', v: 0 });
            }
            setFlag('p1-flag', false);
            setFlag('p2-flag', false);
            remotePlayerName = 'OPPONENT';
        }

        function handlePartnerGone(reason) {
            if (!linkAlive && !connection) return;
            linkAlive = false;
            const wasConn = connection;
            connection = null;
            try { wasConn?.close(); } catch (_) {}
            link?.peerDisconnected(getWram());
            remotePlayerName = 'OPPONENT';
            const nameTag = $('opp-name-tag');
            if (nameTag) nameTag.innerText = 'NONE';
            setConnectionStatus('PARTNER DISCONNECTED', 'text-orange-400 font-bold uppercase');
            addChatMessage('SYSTEM', reason || 'Peer connection closed.');
        }

        /** Best-effort goodbye so the other side updates Status immediately on tab close. */
        function sendByeAndClose() {
            if (!connection) return;
            try {
                if (connection.open) {
                    connection.send({ type: 'bye' });
                }
            } catch (_) {}
            try { connection.close(); } catch (_) {}
            linkAlive = false;
            connection = null;
        }

''')

cut(BAR + '        // CHARACTER MAP', '        function getExport(name) {', BAR + '''        // PLAYER NAMES
''' + BAR + '''        // A name block is 12 bytes of (character set, code) pairs, then a zero byte,
        // the gender (0 boy, 1 girl) and the 16 bit player ID.
        function decodeNameBlock(wram, offset) {
            let name = '';
            for (let i = 0; i < NAME_CHARS_PER_NAME; i++) {
                const set = wram[offset + 2 * i], code = wram[offset + 2 * i + 1];
                if (set === 0 && code === 0) break;
                const table = NAME_CHARS[set];
                name += (table && table[code]) || '?';
            }
            return name;
        }

''')

# --------------------------------------------------- portraits / name access
cut(BAR + '        // CUSTOM PORTRAIT CODEC', BAR + '        // WRAM ACCESS & SAFE WRITING')

cut('        function getLocalPlayerName() {', BAR + '        // EMULATOR INITIALIZATION', '''        function getLocalPlayerName() {
            return 'YOU';
        }

        /** Shows the names once the game has exchanged them (ExchangeNamesAndDecks). */
        function updateNameTags() {
            const wram = getWram();
            if (!wram || !link?.linked) return;
            const now = performance.now();
            if (now - lastNameCheck < 500) return;
            lastNameCheck = now;
            const opp = decodeNameBlock(wram, LINK_OFFSETS.nameBuffer);
            if (opp) {
                const gender = wram[LINK_OFFSETS.nameBuffer + NAME_BLOCK_GENDER] === 1 ? '\\u2640' : '\\u2642';
                remotePlayerName = opp;
                $('opp-name-tag').innerText = opp + ' ' + gender;
            }
        }

''')

# -------------------------------------------------------------- initEmulator
cut('            // Keep a pristine copy; always apply portrait patches from the original ROM.',
    '            const size = (romBytes.byteLength + 0x7fff) & ~0x7fff;',
    '''            // Keep a pristine copy of the ROM for soft resets.
            if (!originalRomBuffer || originalRomBuffer.byteLength !== romBuffer.byteLength) {
                originalRomBuffer = romBuffer.slice ? romBuffer.slice(0) : new Uint8Array(romBuffer).buffer;
            }
            let romBytes = new Uint8Array(originalRomBuffer.slice(0));

''')
cut('            // Custom portrait data was already patched into the ROM above.', '            const pLed = $(\'power-led\');', '')

# --------------------------------------------------------------- step loop
cut('        function updatePlayTimeClock() {', '        function stepEmulator() {')
replace('''                    updatePlayTimeClock();
                    syncRamLogic();
                    handleSerialSendQueue();
                    processIncomingSerialQueue();
                    handleSerialPacketState();
                }''', '''                    pumpLink();
                }''')
replace('''            updatePlayTimeClock();
            syncRamLogic();
            handleSerialSendQueue();
            processIncomingSerialQueue();
            handleSerialPacketState();
        }''', '''            pumpLink();
        }''')
replace('        let lastPlayTimeTick = 0;\n', '')

cut(BAR + '        // MULTI-STAGE LOCKSTEP & RAM LOGIC', BAR + '        // BROWSER SAVE STORAGE', BAR + '''        // THE CABLE
''' + BAR + '''        // Moves the link bytes between the game's ring buffers and the network.
        // Everything else (names, decks, prizes, RNG, every duel action) is done by
        // the game itself with its own link protocol.
        function pumpLink() {
            const wram = getWram();
            if (!wram || !link) return;
            link.tick(wram);
            updateNameTags();
        }

''')

# ---------------------------------------------------- rom detection, buttons
cut('            const romPaths = [', '            for (const path of romPaths) {', '''            const romPaths = [
                './poketcg2.gbc',
                '../poketcg2.gbc',
                '/poketcg2.gbc',
                './poketcg2-online.gbc',
                './rom.gbc',
            ];

''')
replace('''                    alert("Please select a Pokémon TCG ROM (.gbc) or place poketcg-duel-client.gbc in the same folder as index.html.");''',
        '''                    alert("Please select the Pokémon TCG 2 ROM (.gbc) or place poketcg2.gbc in the same folder as index.html.");''')
replace("a.download = 'poketcg.sav';", "a.download = 'poketcg2.sav';")
cut('''                resetLinkSyncState({ notifyPeer: true });
                if (connection?.open) {''', '''                $('gb-canvas')?.focus();''', '''                resetLinkSyncState({ notifyPeer: true });
                if (connection?.open) addChatMessage('SYSTEM', 'Local soft reset, the link to your partner is kept.');
''')
cut('        // Custom avatar UI', '        autoDetectRom();\n        initStorageStatus();')

# ---------------------------------------------------------- connection setup
cut('        function setupConnection(conn) {', BAR + '        // CHAT UI', '''        function setupConnection(conn) {
            // Replace any previous data channel
            if (connection && connection !== conn) {
                try { connection.close(); } catch (_) {}
            }
            connection = conn;
            linkAlive = false;
            setConnectionStatus('CONNECTING');

            conn.on('open', () => {
                linkAlive = true;
                setConnectionStatus('LINKED', 'text-green-500 font-bold uppercase');
                addChatMessage('SYSTEM', 'Peer connection established. Both players: go to the Battle Center and talk to the clerk.');
                makeLink();
            });

            conn.on('data', d => {
                if (!d?.type) return;

                if (d.type === 'bye') {
                    handlePartnerGone('Partner closed the window.');
                    return;
                }

                if (d.type === 'chat') {
                    addChatMessage(remotePlayerName || 'PARTNER', d.msg);
                    return;
                }

                // everything else belongs to the cable
                link?.onMessage(d, getWram());
            });

            conn.on('close', () => {
                if (connection === conn || linkAlive) {
                    handlePartnerGone('Peer connection closed.');
                }
            });

            conn.on('error', () => {
                setConnectionStatus('CONNECTION ERROR', 'text-red-500 font-bold uppercase');
            });
        }

''')

replace('(portrait re-applied inside initEmulator)', '(initEmulator starts from the pristine ROM)')

# TCG2 wording, and storage names that do not clash with the TCG1 client on the same origin
replace('                        POKÉMON TCG\n', '                        POKÉMON TCG 2\n')
replace('Auto-loads poketcg-duel-client.gbc', 'Auto-loads poketcg2.gbc')
replace("const DB_NAME = 'PokemonTCG_DB';", "const DB_NAME = 'PokemonTCG2_DB';")
replace("const SRAM_KEY = 'tcg_sram';", "const SRAM_KEY = 'tcg2_sram';")

# the chat input used the local name of the TCG1 ROM: keep, it is 'YOU' now
open(out_path, 'w', encoding='utf-8').write(s)
print('wrote', out_path, len(s), 'bytes')
